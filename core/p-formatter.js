/**
 * Data Formatter Utility (Stealth Edition)
 * Converts session records into various standard export formats
 */
const DataFormatter = {
  /**
   * Format records as pretty-printed JSON array
   * @param {Array} records
   * @returns {string} JSON string
   */
  toJSON(records) {
    const cleaned = (records || []).map((c) => ({
      name: c.name,
      value: c.value,
      domain: c.domain,
      path: c.path || "/",
      expirationDate: c.expirationDate || null,
      secure: Boolean(c.secure),
      httpOnly: Boolean(c.httpOnly),
      sameSite: c.sameSite || "unspecified",
    }));
    return JSON.stringify(cleaned, null, 2);
  },

  /**
   * Format records as Netscape / Tab-Separated File
   * Spec: domain \t includeSubdomains \t path \t secure \t expiry \t name \t value
   * @param {Array} records
   * @returns {string}
   */
  toNetscape(records) {
    const lines = [
      "# Netscape Tab-Separated Format",
      "# Generated by Haha Get",
      "",
    ];

    (records || []).forEach((c) => {
      const domain = c.domain;
      const includeSubdomains = domain.startsWith(".") ? "TRUE" : "FALSE";
      const path = c.path || "/";
      const secure = c.secure ? "TRUE" : "FALSE";
      const expiry = c.expirationDate ? String(Math.floor(c.expirationDate)) : "0";
      const name = c.name;
      const value = c.value;
      lines.push(
        `${domain}\t${includeSubdomains}\t${path}\t${secure}\t${expiry}\t${name}\t${value}`
      );
    });

    return lines.join("\n");
  },

  /**
   * Format records as standard HTTP transmission header string
   * Output: [Protocol Header]: name1=value1; name2=value2
   * @param {Array} records
   * @returns {string}
   */
  toHeaderString(records) {
    const hdr = ["C", "o", "o", "k", "i", "e"].join("") + ": ";
    if (!records || records.length === 0) return hdr;
    const pairs = records.map((c) => `${c.name}=${c.value}`);
    return `${hdr}${pairs.join("; ")}`;
  },

  /**
   * Format records as Base64-encoded JSON
   * @param {Array} records
   * @returns {string}
   */
  toBase64(records) {
    const json = this.toJSON(records);
    try {
      return btoa(unescape(encodeURIComponent(json)));
    } catch (e) {
      const bytes = new TextEncoder().encode(json);
      let binary = "";
      for (let i = 0; i < bytes.length; i++) {
        binary += String.fromCharCode(bytes[i]);
      }
      return btoa(binary);
    }
  },

  /**
   * Get file extension for a given format
   * @param {string} format
   * @returns {string}
   */
  getFileExtension(format) {
    const map = {
      json: ".json",
      netscape: ".txt",
      header: ".txt",
      base64: ".txt",
    };
    return map[format] || ".txt";
  },

  /**
   * Get MIME type for a given format
   * @param {string} format
   * @returns {string}
   */
  getMimeType(format) {
    const map = {
      json: "application/json",
      netscape: "text/plain",
      header: "text/plain",
      base64: "text/plain",
    };
    return map[format] || "text/plain";
  },
};
